#!/usr/bin/env node
/**
 * Migrate Strapi landing + global settings → Postgres CMS tables (direct SQL).
 * Loads STRAPI_* from therapyflow-website/.env and DB_* from env or application-local defaults.
 *
 * Usage: node scripts/migrate-strapi-landing-sql.mjs
 */

import { readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Client } from "pg";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const websiteEnv = join(root, "../../therapyflow-website/.env");
const localYml = join(root, "src/main/resources/application-local.yml");

function loadDotEnv(path) {
  if (!existsSync(path)) return {};
  const out = {};
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!m) continue;
    let v = m[2].trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      v = v.slice(1, -1);
    }
    out[m[1]] = v;
  }
  return out;
}

function parseLocalYmlDb() {
  if (!existsSync(localYml)) return {};
  const text = readFileSync(localYml, "utf8");
  const url = text.match(/url:\s*\$\{DB_URL:(jdbc:postgresql:\/\/[^}]+)\}/)?.[1];
  const username = text.match(/username:\s*\$\{DB_USERNAME:([^}]+)\}/)?.[1];
  const password = text.match(/password:\s*\$\{DB_PASSWORD:([^}]+)\}/)?.[1];
  return { url, username, password };
}

function jdbcToPgConfig(jdbcUrl, username, password) {
  // jdbc:postgresql://host:5432/db
  const m = jdbcUrl.match(/^jdbc:postgresql:\/\/([^:/]+)(?::(\d+))?\/([^?]+)/);
  if (!m) throw new Error("Cannot parse JDBC URL: " + jdbcUrl);
  return {
    host: m[1],
    port: Number(m[2] || 5432),
    database: m[3],
    user: username,
    password,
    ssl: { rejectUnauthorized: false },
  };
}

const website = loadDotEnv(websiteEnv);
const STRAPI_URL = (process.env.STRAPI_URL || website.VITE_STRAPI_API_URL || "https://strapi-admin.therapyflow.pro").replace(/\/$/, "");
const STRAPI_TOKEN = process.env.STRAPI_TOKEN || website.VITE_STRAPI_API_TOKEN || "";

const ymlDb = parseLocalYmlDb();
const jdbcUrl = process.env.DB_URL || ymlDb.url;
const dbUser = process.env.DB_USERNAME || ymlDb.username;
const dbPass = process.env.DB_PASSWORD || ymlDb.password;

const LANDING_POPULATE = [
  "populate[Header_Logo]=true",
  "populate[Header_Nav_Links]=true",
  "populate[Hero_Image]=true",
  "populate[Features_Tabs_List][populate][Preview_Image]=true",
  "populate[Customization_Cards][populate][Graphic_Image]=true",
  "populate[Communication_Cards]=true",
  "populate[Security_Cards][populate][Image]=true",
  "populate[Benefits_Cards]=true",
  "populate[Faq_List]=true",
  "populate[Footer_Logo]=true",
  "populate[Footer_Nav_Links]=true",
  "populate[Footer_Socials]=true",
  "populate[Footer_Legal_Links]=true",
  "populate[SEO][populate][OG_Image]=true",
].join("&");

const GLOBAL_POPULATE = [
  "populate[Default_OG_Image]=true",
  "populate[Organization_Logo]=true",
  "populate[Landing_SEO][populate][OG_Image]=true",
  "populate[LearningHub_SEO][populate][OG_Image]=true",
].join("&");

async function fetchJson(url, headers = {}) {
  const res = await fetch(url, { headers: { Accept: "application/json", ...headers } });
  if (!res.ok) {
    const body = await res.text().catch(() => "");
    throw new Error(`GET ${url} → ${res.status}\n${body}`);
  }
  return res.json();
}

function absoluteMediaUrl(url) {
  if (!url) return url;
  if (/^https?:\/\//i.test(url)) return url;
  return `${STRAPI_URL}${url.startsWith("/") ? "" : "/"}${url}`;
}

function normalizeMedia(node) {
  if (node == null) return node;
  if (Array.isArray(node)) return node.map(normalizeMedia);
  if (typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "url" && typeof value === "string") out[key] = absoluteMediaUrl(value);
    else out[key] = normalizeMedia(value);
  }
  return out;
}

function stripMeta(node) {
  if (node == null) return node;
  if (Array.isArray(node)) return node.map(stripMeta);
  if (typeof node !== "object") return node;
  const skip = new Set([
    "id", "documentId", "createdAt", "updatedAt", "publishedAt",
    "locale", "localizations", "createdBy", "updatedBy",
  ]);
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (skip.has(key)) continue;
    out[key] = stripMeta(value);
  }
  return out;
}

const SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS cms_global_settings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content         JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_by_auth_id BIGINT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS cms_landing_page (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_content       JSONB NOT NULL DEFAULT '{}'::jsonb,
    published_content   JSONB,
    published_at        TIMESTAMPTZ,
    updated_by_auth_id  BIGINT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS cms_media_asset (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storage_key     VARCHAR(512) NOT NULL,
    public_url      VARCHAR(1024) NOT NULL,
    filename        VARCHAR(255) NOT NULL,
    mime_type       VARCHAR(128),
    size_bytes      BIGINT,
    alt_text        VARCHAR(255),
    width           INTEGER,
    height          INTEGER,
    uploaded_by_auth_id BIGINT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
`;

async function main() {
  console.log("── Strapi → Postgres CMS migration (SQL) ──");
  console.log("Strapi:", STRAPI_URL);
  console.log("DB host:", jdbcToPgConfig(jdbcUrl, dbUser, dbPass).host);

  const headers = {};
  if (STRAPI_TOKEN) headers.Authorization = `Bearer ${STRAPI_TOKEN}`;

  console.log("Fetching landing page…");
  const landingRes = await fetchJson(`${STRAPI_URL}/api/landing-page?${LANDING_POPULATE}`, headers);
  const landing = stripMeta(normalizeMedia(landingRes.data));
  console.log("  Landing keys:", Object.keys(landing).length);

  console.log("Fetching global settings…");
  const globalRes = await fetchJson(`${STRAPI_URL}/api/global-site-settings?${GLOBAL_POPULATE}`, headers);
  const globalSettings = stripMeta(normalizeMedia(globalRes.data));
  console.log("  Global keys:", Object.keys(globalSettings).length);

  const client = new Client(jdbcToPgConfig(jdbcUrl, dbUser, dbPass));
  await client.connect();
  try {
    console.log("Ensuring CMS tables…");
    await client.query(SCHEMA_SQL);

    // Ensure single rows exist
    await client.query(`
      INSERT INTO cms_landing_page (draft_content)
      SELECT '{}'::jsonb WHERE NOT EXISTS (SELECT 1 FROM cms_landing_page)
    `);
    await client.query(`
      INSERT INTO cms_global_settings (content)
      SELECT '{}'::jsonb WHERE NOT EXISTS (SELECT 1 FROM cms_global_settings)
    `);

    console.log("Writing landing page (draft + published)…");
    await client.query(
      `UPDATE cms_landing_page
       SET draft_content = $1::jsonb,
           published_content = $1::jsonb,
           published_at = NOW(),
           updated_at = NOW()
       WHERE id = (SELECT id FROM cms_landing_page ORDER BY id LIMIT 1)`,
      [JSON.stringify(landing)],
    );

    console.log("Writing global settings…");
    await client.query(
      `UPDATE cms_global_settings
       SET content = $1::jsonb,
           updated_at = NOW()
       WHERE id = (SELECT id FROM cms_global_settings ORDER BY id LIMIT 1)`,
      [JSON.stringify(globalSettings)],
    );

    const check = await client.query(
      `SELECT
         (SELECT COUNT(*) FROM jsonb_object_keys(draft_content)) AS landing_keys,
         published_at,
         (SELECT COUNT(*) FROM cms_landing_page) AS landing_rows
       FROM cms_landing_page ORDER BY id LIMIT 1`,
    );
    const check2 = await client.query(
      `SELECT
         (SELECT COUNT(*) FROM jsonb_object_keys(content)) AS global_keys,
         (SELECT COUNT(*) FROM cms_global_settings) AS global_rows
       FROM cms_global_settings ORDER BY id LIMIT 1`,
    );
    console.log("Verify landing:", check.rows[0]);
    console.log("Verify global:", check2.rows[0]);
    console.log("\nMigration complete. Restart the backend so CMS APIs pick up the new code + tables.");
  } finally {
    await client.end();
  }
}

main().catch((err) => {
  console.error("\nMigration failed:", err.message || err);
  process.exit(1);
});
